"""Phase 4 Step 2: the web interface (talks to the API).

    python -m text2sql.api            # or: python -m text2sql.api --demo
    streamlit run ui/streamlit_app.py
"""
from __future__ import annotations

import os
import uuid

import httpx
import pandas as pd
import streamlit as st

try:  # SQL editor with syntax highlighting; plain text box if not installed
    from streamlit_ace import st_ace
except ImportError:
    st_ace = None

API_URL = os.environ.get("TEXT2SQL_API_URL", "http://127.0.0.1:8000")
BAND_COLOURS = {"high": "green", "medium": "orange", "low": "red"}
SIGNAL_LABELS = {
    "syntax": "Valid SQL", "alignment": "Back-translation match", "sanity": "Result checks",
    "agreement": "Second query agrees", "coverage": "Covers the question", "model": "Model's own estimate",
}
STATUS_MESSAGES = {
    "invalid_sql": "The model couldn't produce valid SQL",
    "blocked": "Blocked by the guardrails",
    "timeout": "The query took too long and was stopped",
    "denied": "The database refused this query",
    "query_error": "The query failed",
    "generation_failed": "Couldn't generate SQL",
    "cannot_answer": "This can't be answered from the database",
}

st.set_page_config(page_title="Text-to-SQL", page_icon="🔎", layout="wide")
state = st.session_state
state.setdefault("session_id", uuid.uuid4().hex[:16])
state.setdefault("current", None)
state.setdefault("feedback_sent", set())


@st.cache_resource
def client() -> httpx.Client:
    # Long timeout: generation plus verification can take a while.
    return httpx.Client(base_url=API_URL, timeout=300)


def call(method: str, path: str, **kwargs):
    try:
        response = client().request(method, path, **kwargs)
    except httpx.HTTPError as e:
        st.error(f"Can't reach the API at {API_URL} ({type(e).__name__}). "
                 f"Start it with `python -m text2sql.api`.")
        st.stop()
    if response.status_code >= 400:
        detail = response.json().get("detail", response.text) if response.content else response.text
        st.error(f"API error {response.status_code}: {detail}")
        return None
    return response.json()


@st.cache_data(ttl=300)
def load_schema() -> dict:
    return client().get("/v1/schema").json()


# --- sidebar: history and schema --------------------------------------------------

health = call("GET", "/v1/health")
with st.sidebar:
    st.header("History")
    history = call("GET", "/v1/history", params={"session_id": state.session_id}) or {"items": []}
    if not history["items"]:
        st.caption("Your questions will appear here.")
    for item in history["items"]:
        band = item.get("confidence_band")
        marker = {"high": "🟢", "medium": "🟠", "low": "🔴"}.get(band, "⚪")
        if item["status"] == "needs_clarification":
            marker = "❓"
        label = f"{marker} {item['question'][:60]}"
        if st.button(label, key=f"h-{item['request_id']}-{item['status']}",
                     use_container_width=True):
            state.current = item

    st.divider()
    with st.expander("Database schema"):
        schema = load_schema()
        for table in schema["tables"]:
            rows = f" · {table['row_count']:,} rows" if table["row_count"] else ""
            st.markdown(f"**{table['name']}**{rows}  \n{table['description'] or ''}")
            for c in table["columns"]:
                extra = " 🔒 personal data" if c["sensitive"] else ""
                values = f" — {', '.join(map(str, c['values'][:6]))}" if c.get("values") else ""
                st.caption(f"`{c['name']}` {c['type']}{extra}{values}")
    st.caption(f"Session `{state.session_id}`")


# --- main: ask ----------------------------------------------------------------------

st.title("Ask your database")
if health and health.get("demo"):
    st.info("**Demo mode**: answers are replayed from the verified example library, not "
            "generated by Claude. Set `ANTHROPIC_API_KEY` and restart the API without "
            "`--demo` for real answers.")

with st.form("ask", clear_on_submit=False):
    question = st.text_input("Question", placeholder="e.g. What was net revenue by country last quarter?")
    asked = st.form_submit_button("Ask", type="primary")
if asked and question.strip():
    with st.spinner("Writing SQL, running it, and checking the answer…"):
        state.current = call("POST", "/v1/query",
                             json={"question": question, "session_id": state.session_id})
    st.rerun()

current = state.current
if current is None:
    st.caption("Ask a question about orders, customers, products or support tickets.")
    st.stop()

st.subheader(current["question"])

# --- clarification ------------------------------------------------------------------

if current["status"] == "needs_clarification":
    st.warning(current["prompt"])
    labels = [f"{o['label']}: {o['description']}" for o in current["options"]]
    for option in current["options"]:
        with st.expander(f"Preview: {option['label']}"):
            st.code(option["sql"], language="sql")
            if option["columns"]:
                st.dataframe(pd.DataFrame(option["preview_rows"], columns=option["columns"]),
                             hide_index=True)
            elif option["error"]:
                st.error(option["error"])
    pick = st.radio("Which did you mean?", range(len(labels)), format_func=lambda i: labels[i])
    if st.button("Use this meaning", type="primary"):
        with st.spinner("Running it…"):
            state.current = call("POST", f"/v1/query/{current['request_id']}/choose",
                                 json={"session_id": state.session_id, "option": pick})
        st.rerun()
    st.stop()

# --- answer ------------------------------------------------------------------------

left, right = st.columns([3, 2])

with right:
    band = current.get("confidence_band")
    if band:
        st.markdown(f"### Confidence: :{BAND_COLOURS[band]}[{band.upper()}]")
        st.progress(current["confidence"], text=f"{current['confidence']:.2f}")
        report = current.get("verification") or {}
        conf = report.get("confidence") or {}
        for problem in conf.get("problems", []):
            st.markdown(f"⚠️ {problem}")
        for support in conf.get("support", []):
            st.markdown(f"✅ {support}")
        with st.expander("Signal breakdown"):
            for key, value in (conf.get("signals") or {}).items():
                name = SIGNAL_LABELS.get(key, key)
                if value is None:
                    st.caption(f"{name}: not measured")
                else:
                    st.progress(float(value), text=f"{name}: {value:.2f}")
            if conf.get("caps"):
                st.caption("Capped by: " + ", ".join(conf["caps"]))
            for note in report.get("notes", []):
                st.caption(f"Note: {note}")
    elif current.get("confidence_reasons"):
        st.warning(current["confidence_reasons"][0])

    notes = ([f"Assumption: {a}" for a in current.get("assumptions", [])]
             + [f"Guardrails: {r}" for r in current.get("rewrites", [])]
             + [f"Warning: {w}" for w in current.get("warnings", [])])
    if current.get("attempts", 0) > 1:
        notes.append(f"Fixed after {current['attempts'] - 1} rejected attempt(s)")
    if notes:
        st.markdown("**Notes**")
        for n in notes:
            st.caption(n)

with left:
    if current.get("explanation"):
        st.write(current["explanation"])
    if current.get("sql"):
        source = " (edited by you)" if current.get("source") == "user" else ""
        st.markdown(f"**SQL{source}**")
        st.code(current["sql"], language="sql")
        with st.expander("Edit and run SQL"):
            original = current.get("generated_sql") or current["sql"]
            key = f"edit-{current['request_id']}"
            if st_ace is not None:
                edited = st_ace(value=original, language="sql", theme="tomorrow",
                                min_lines=6, max_lines=20, font_size=14, wrap=True,
                                auto_update=True, key=key)
            else:
                edited = st.text_area("SQL", original, height=180, key=key)
            if st.button("Run edited SQL"):
                with st.spinner("Checking and running…"):
                    state.current = call("POST", "/v1/sql", json={
                        "sql": edited, "session_id": state.session_id,
                        "question": current["question"]})
                st.rerun()

    if current["status"] != "ok":
        detail = (current.get("error") or current.get("explanation", "")).removeprefix(
            "Blocked by guardrails: ")
        st.error(f"**{STATUS_MESSAGES.get(current['status'], 'Failed')}**: {detail}")
        if current["status"] in ("blocked", "denied"):
            st.caption("Nothing was run against the database. Generated SQL is only ever "
                       "executed read-only, after these checks.")
    else:
        df = pd.DataFrame(current["rows"], columns=current["columns"])
        st.dataframe(df, hide_index=True, use_container_width=True)  # click headers to sort
        timing = f"{current['row_count']} row(s)"
        if current.get("execution_ms") is not None:
            timing += f" · {current['execution_ms']:.0f} ms in the database"
        if current.get("total_ms") is not None:
            timing += f" · {current['total_ms'] / 1000:.1f} s total"
        st.caption(timing)
        if current.get("truncated"):
            st.warning(f"More rows exist; showing the first {current['row_count']}.")
        st.download_button("Download CSV", df.to_csv(index=False), "result.csv", "text/csv")

        mq = (current.get("verification") or {}).get("multiquery") or {}
        if mq.get("ran") and mq.get("agreed") is False:
            st.markdown("**An independent second query disagrees**")
            st.caption(f"{mq.get('explanation', '')}. "
                       f"{mq.get('alternative_explanation', '')}")
            st.code(mq.get("alternative_sql") or "", language="sql")
            st.dataframe(pd.DataFrame(mq.get("alternative_rows") or [],
                                      columns=mq.get("alternative_columns") or None),
                         hide_index=True)
            # Resolve it: run the alternative through the same checks and see
            # which answer survives them.
            if st.button("Use the second approach", key=f"alt-{current['request_id']}"):
                with st.spinner("Checking the second approach…"):
                    state.current = call("POST", "/v1/sql", json={
                        "sql": mq["alternative_sql"], "session_id": state.session_id,
                        "question": current["question"]})
                st.rerun()
        if current.get("plan"):
            with st.expander("Query plan"):
                if current.get("estimated_scan_rows") is not None:
                    st.caption(f"Estimated rows read: {current['estimated_scan_rows']:,}")
                st.code("\n".join(current["plan"]), language="text")

# --- feedback ------------------------------------------------------------------------

if current["status"] == "ok":
    st.divider()
    rid = current["request_id"]
    if rid in state.feedback_sent:
        st.success("Thanks, your feedback was recorded for review.")
    else:
        st.markdown("**Was this answer correct?**")
        good, bad = st.columns(2)
        if good.button("👍 Correct", use_container_width=True):
            if call("POST", "/v1/feedback", json={"session_id": state.session_id,
                                                  "request_id": rid, "verdict": "correct"}):
                state.feedback_sent.add(rid)
                st.rerun()
        with bad.popover("👎 Incorrect", use_container_width=True):
            fix = st.text_area("Correct SQL (optional, makes this a test case)",
                               current.get("sql") or "", height=150, key=f"fix-{rid}")
            comment = st.text_input("What's wrong?", key=f"why-{rid}")
            if st.button("Send", key=f"send-{rid}"):
                changed = fix.strip() and fix.strip() != (current.get("sql") or "").strip()
                if call("POST", "/v1/feedback", json={
                        "session_id": state.session_id, "request_id": rid,
                        "verdict": "incorrect", "comment": comment,
                        "corrected_sql": fix if changed else None}):
                    state.feedback_sent.add(rid)
                    st.rerun()
